// Helper function to get all villages sorted
export const getAllKamareddyVillages = () => {
  return [...new Set(KAMAREDDY_VILLAGES)].sort();
};

// Helper function to search villages
export const searchKamareddyVillages = (searchTerm: string) => {
  return KAMAREDDY_VILLAGES.filter(village => 
    village.toLowerCase().includes(searchTerm.toLowerCase())
  ).sort();
};
